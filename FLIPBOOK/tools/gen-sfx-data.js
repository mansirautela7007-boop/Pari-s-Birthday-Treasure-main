/*
 * Regenerate sfx-data.js from the CONVERTED Ogg/Opus one-shots.
 * The old file inlined the mp3s; leaving it alone would have shipped the very
 * bytes the conversion removed, twice over (base64 is +33%).
 */
const fs = require('fs');
const path = require('path');
const ROOT = process.argv[2];

const SRC = {
  cover: 'sfx/cover page flip.ogg',
  flip: 'sfx/Page flip.ogg',
};

let out = `// AUTO-GENERATED by tools/gen-sfx-data.js — do not edit by hand.
//
// The two one-shot SFX inlined as base64 data URIs so they can be fetched and
// decoded by the Web Audio API even when the page is opened via file://, where
// fetch/XHR of a plain file path is blocked. Used by script.js for glitch-free,
// zero-latency cover-flip / page-flip sounds.
//
// Format: Ogg (Opus, 64 kbps) — Chrome, Edge, Firefox, Safari 17.4+. Note that
// decodeAudioData works on the raw bytes and does NOT need the browser to
// support the container in an <audio> element, so this path also carries older
// Safari, where sfx/*.ogg as an element source would not play.
//
// The background music stays a normal <audio> (a long ambient loop where start
// latency does not matter) and is not inlined here.
window.SFX_DATA = {
`;

let total = 0;
for (const [key, rel] of Object.entries(SRC)) {
  const buf = fs.readFileSync(path.join(ROOT, rel));
  const b64 = buf.toString('base64');
  total += b64.length;
  out += `  // ${rel} — ${buf.length} bytes\n  ${key}: "data:audio/ogg;base64,${b64}",\n`;
}
out += '};\n';

const dst = path.join(ROOT, 'sfx-data.js');
const before = fs.existsSync(dst) ? fs.statSync(dst).size : 0;
fs.writeFileSync(dst, out);
const after = fs.statSync(dst).size;
console.log(`sfx-data.js ${before} -> ${after} bytes (${((1 - after / before) * 100).toFixed(1)}% smaller)`);
